@dataclass
class SignalAssessment:
    signal: str                     # spatial | frequency | temporal
    score: Optional[float]          # P(fake), None if unavailable
    reliability: str                # reliable | limited | unreliable | unavailable
    contributes_to_verdict: bool    # trustworthy AND actually weighted by Fusion
    separation: float               # audit context: fake_avg - real_avg
    note: str                       # plain-language reliability note


@dataclass
class Caveat:
    code: str                       # stable machine-readable code, e.g. TEMPORAL_UNAVAILABLE
    severity: str                   # "warning" | "info"
    text: str


@dataclass
class TrackReasoning:
    track_id: Any
    verdict: str                    # FAKE | REAL | INCONCLUSIVE
    model_verdict: str              # raw Fusion call (FAKE | REAL), never altered
    confidence: str                 # Low | Medium | High
    confidence_reasons: List[str]
    fusion_prob_fake: float
    signals: List[SignalAssessment]
    caveats: List[Caveat]
    quality_level: str              # good | degraded | poor | unknown
    explanation: str
    explanation_source: str         # "llm" | "rule_based"

    def to_dict(self) -> dict:
        return asdict(self)


@dataclass
class ReasoningReport:
    schema_version: str
    input_type: str
    overall_verdict: str            # FAKE | REAL | INCONCLUSIVE
    overall_confidence: str
    driving_track_id: Any
    tracks: List[TrackReasoning]
    notes: List[Caveat]             # file-level notes (e.g. no faces found)

    def to_dict(self) -> dict:
        return asdict(self)

    def to_forensic_manager_dict(self) -> dict:
        """
        PROVISIONAL adapter to the shape of the frontend's
        forensic_analysis_manager_response.json (0-100 scores). Update once
        the real 4B contract is fixed. score_weights is omitted on purpose:
        we have no honest per-signal weights to report.
        """
        t = next((x for x in self.tracks if x.track_id == self.driving_track_id), None)
        if t is None:
            return {
                "final_score": None, "classification": "Inconclusive",
                "confidence_level": "Low", "spatial_score": None, "temporal_score": None,
                "frequency_score": None, "metadata_score": None, "source_score": None,
                "models_used": [], "models_skipped": [], "top_contributing_signal": None,
                "forensic_reasoning": [c.text for c in self.notes], "media_type": self.input_type,
            }

        if self.overall_verdict == "INCONCLUSIVE":
            classification = "Inconclusive"
        elif self.overall_verdict == "FAKE":
            classification = "Likely Fake" if self.overall_confidence != "Low" else "Suspicious"
        else:
            classification = "Likely Real" if self.overall_confidence != "Low" else "Inconclusive"

        def pct(sig: SignalAssessment):
            if sig.score is None or sig.reliability in ("unavailable", "unreliable"):
                return None
            return round(sig.score * 100)

        by_name = {s.signal: s for s in t.signals}
        used = [f"{DISPLAY[s.signal]} Analysis" for s in t.signals if s.contributes_to_verdict]
        skipped = [f"{DISPLAY[s.signal]} Analysis - {s.reliability}" +
                   ("" if s.reliability != "reliable" else " but not weighted by the deployed Fusion model")
                   for s in t.signals if not s.contributes_to_verdict]
        contributing = [s for s in t.signals if s.contributes_to_verdict]
        top = max(contributing, key=lambda s: s.separation).signal if contributing else None

        return {
            "final_score": round(t.fusion_prob_fake * 100),
            "classification": classification,
            "confidence_level": self.overall_confidence,
            "spatial_score": pct(by_name["spatial"]),
            "temporal_score": pct(by_name["temporal"]),
            "frequency_score": pct(by_name["frequency"]),
            "metadata_score": None,
            "source_score": None,
            "models_used": used,
            "models_skipped": skipped,
            "top_contributing_signal": f"{DISPLAY[top]} Analysis" if top else None,
            "forensic_reasoning": [s.note for s in t.signals] + [c.text for c in t.caveats],
            "media_type": self.input_type,
        }


