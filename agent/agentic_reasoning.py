class LLMClient(Protocol):
    def complete(self, system: str, user: str) -> str: ...


class AnthropicClient:
    """Thin wrapper. Needs `pip install anthropic` and ANTHROPIC_API_KEY."""

    def __init__(self, model: Optional[str] = None, api_key: Optional[str] = None,
                 timeout: float = 20.0, max_tokens: int = 500):
        import anthropic  # lazy: rule-based mode must work without it
        self._client = anthropic.Anthropic(api_key=api_key, timeout=timeout, max_retries=1)
        self.model = model or os.environ.get("REASONING_MODEL", "claude-haiku-4-5-20251001")
        self.max_tokens = max_tokens

    def complete(self, system: str, user: str) -> str:
        resp = self._client.messages.create(
            model=self.model, max_tokens=self.max_tokens, system=system,
            messages=[{"role": "user", "content": user}],
        )
        return "".join(b.text for b in resp.content if getattr(b, "type", "") == "text")


class OllamaClient:
    """
    Local LLM through an Ollama server (default: Gemma 2 9B in the ollama-gpu
    container on port 11435). No API key, works offline.
    Env: OLLAMA_URL, OLLAMA_MODEL.
    """

    def __init__(self, url: Optional[str] = None, model: Optional[str] = None,
                 timeout: float = 90.0, max_tokens: int = 400):
        import requests  # lazy, like the Anthropic SDK above
        self._requests = requests
        self.url = (url or os.environ.get("OLLAMA_URL", "http://localhost:11435")).rstrip("/")
        self.model = model or os.environ.get("OLLAMA_MODEL", "gemma2:latest")
        self.timeout = timeout
        self.max_tokens = max_tokens

    def complete(self, system: str, user: str) -> str:
        resp = self._requests.post(f"{self.url}/api/chat", timeout=self.timeout, json={
            "model": self.model, "stream": False, "format": "json", "keep_alive": "60m",
            "options": {"temperature": 0.3, "num_predict": self.max_tokens},
            "messages": [{"role": "system", "content": system}, {"role": "user", "content": user}],
        })
        resp.raise_for_status()
        return resp.json()["message"]["content"]


