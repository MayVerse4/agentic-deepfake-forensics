"""
agentic_reasoning.py -- Phase 4A: the reasoning layer that runs AFTER Fusion.

WHAT THIS DOES
--------------
Takes the InferenceEngine's per-track output (Fusion score, per-model
scores, temporal availability, quality metadata) and produces a structured
ReasoningReport: verdict, confidence, per-signal reliability notes,
caveats, and a plain-language explanation. That object is what Phase 4B
consumes.

DESIGN RULES
------------
1. The verdict and confidence are computed DETERMINISTICALLY in Python
   from the Fusion score plus the audit findings (SignalProfile). The LLM
   never decides the verdict; it only writes the narrative explanation.
   It cannot contradict the trained model, and it cannot "forget" a
   caveat, because caveats are generated by rules and always ship in the
   output regardless of what the LLM says.
2. Audit knowledge lives in DEFAULT_SIGNAL_PROFILES. When the Fusion
   retrain lands, edit that one dict (separation scores, ablation
   reliance) -- no logic changes needed.
3. If the LLM is unavailable, times out, or returns something malformed
   or inconsistent, a rule-based explanation is used. The pipeline never
   breaks because of this layer.
4. The LLM only ever sees numbers and fixed strings generated here -- no
   user-supplied text (no filenames), so there is no prompt-injection
   surface.

Score convention (matches inference_engine.py): every score is
P(fake) in [0, 1]; Fusion verdict is FAKE when combined > 0.5.
"""

