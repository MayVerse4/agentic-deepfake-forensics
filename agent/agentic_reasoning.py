def _separation_level(sep: float) -> str:
    if sep < SEP_UNRELIABLE_BELOW:
        return "unreliable"
    if sep < SEP_RELIABLE_AT_LEAST:
        return "limited"
    return "reliable"


@dataclass
class _Assessment:
    verdict: str
    model_verdict: str
    confidence: str
    confidence_reasons: List[str]
    signals: List[SignalAssessment]
    caveats: List[Caveat]
    quality_level: str


class AgenticReasoner:
    def __init__(self,
                 llm_client: Any = "auto",
                 signal_profiles: Optional[Dict[str, SignalProfile]] = None,
                 fusion_profile: Optional[FusionProfile] = None,
                 max_workers: int = 4):
        """
        llm_client: "auto" (REASONING_LLM env: "ollama" (default), "anthropic" or
                    "none"; falls back to rule-based if the backend can't be set up),
                    None (rule-based only), or any object with .complete(system, user).
        """
        self.profiles = signal_profiles or DEFAULT_SIGNAL_PROFILES
        self.fusion_profile = fusion_profile or DEFAULT_FUSION_PROFILE
        self.max_workers = max_workers
        self.llm = self._resolve_llm(llm_client)

    @staticmethod
    def _resolve_llm(llm_client):
        if llm_client != "auto":
            return llm_client
        backend = os.environ.get("REASONING_LLM", "ollama").lower()
        if os.environ.get("REASONING_USE_LLM", "1") == "0" or backend == "none":
            logger.info("Agentic reasoning: LLM disabled -> rule-based explanations.")
            return None
        if backend == "anthropic" and not os.environ.get("ANTHROPIC_API_KEY"):
            logger.info("Agentic reasoning: no ANTHROPIC_API_KEY -> rule-based explanations.")
            return None
        try:
            return AnthropicClient() if backend == "anthropic" else OllamaClient()
        except Exception as e:  # SDK missing etc.
            logger.warning("Agentic reasoning: could not init %s client (%s) -> rule-based.", backend, e)
            return None

    # ------------------------------------------------------------------
    # Public entry points
    # ------------------------------------------------------------------
    def reason(self, engine_output: dict, quality: Optional[QualitySummary] = None,
               sequence_length: Optional[int] = None) -> ReasoningReport:
        input_type = engine_output.get("input_type", "video")
        tracks = engine_output.get("per_track_summary", [])
        inputs = [ReasoningInput.from_engine_output(engine_output, t, quality, sequence_length)
                  for t in tracks]

        notes: List[Caveat] = []
        if not inputs:
            notes.append(Caveat(
                "NO_FACES_ANALYZED", "warning",
                "No usable face track was found, so no model could score this media. "
                "Common causes: no visible face, or frames discarded as too blurry."))
            if quality is not None and quality.level in ("poor", "degraded"):
                notes.append(self._quality_caveat(quality))
            return ReasoningReport(SCHEMA_VERSION, input_type, "INCONCLUSIVE", "Low", None, [], notes)

        if len(inputs) == 1 or not self.llm:
            results = [self.reason_track(i) for i in inputs]
        else:
            with ThreadPoolExecutor(max_workers=min(self.max_workers, len(inputs))) as ex:
                results = list(ex.map(self.reason_track, inputs))

        verdict, conf, driving = self._overall(results)
        return ReasoningReport(SCHEMA_VERSION, input_type, verdict, conf, driving, results, notes)

    def reason_track(self, inp: ReasoningInput) -> TrackReasoning:
        a = self.assess(inp)
        explanation, source = self._explain(inp, a)
        return TrackReasoning(
            track_id=inp.track_id, verdict=a.verdict, model_verdict=a.model_verdict,
            confidence=a.confidence, confidence_reasons=a.confidence_reasons,
            fusion_prob_fake=inp.fusion_prob_fake, signals=a.signals, caveats=a.caveats,
            quality_level=a.quality_level, explanation=explanation, explanation_source=source,
        )

    # ------------------------------------------------------------------
    # Deterministic assessment (no LLM anywhere in here)
    # ------------------------------------------------------------------
    def assess(self, inp: ReasoningInput) -> _Assessment:
        p = inp.fusion_prob_fake
        model_verdict = "FAKE" if p > DECISION_THRESHOLD else "REAL"
        is_image = inp.input_type == "image"

        temporal_raw = inp.temporal_prob_fake
        temporal_from_still = is_image and temporal_raw is not None
        temporal = None if is_image else temporal_raw
        temporal_available = temporal is not None
        padded = bool(temporal_available and inp.frames_seen and inp.sequence_length
                      and inp.frames_seen < inp.sequence_length)

        scores = {"spatial": inp.spatial_prob_fake, "frequency": inp.frequency_prob_fake,
                  "temporal": temporal}

        caveats: List[Caveat] = []
        signals: List[SignalAssessment] = []

        for name in ("spatial", "frequency", "temporal"):
            prof = self.profiles[name]
            score = scores[name]
            if score is None:
                reliability, contributes = "unavailable", False
                reason = "no score was produced"
                if name == "temporal":
                    reason = ("still image, so there is no frame sequence" if is_image else
                              "no usable frame sequence for this person")
                    if temporal_from_still:
                        reason = "the score came from a single repeated frame and was disregarded"
                note = f"{DISPLAY[name]}: not available ({reason})."
            else:
                reliability = _separation_level(prof.separation)
                if name == "temporal" and padded and reliability == "reliable":
                    reliability = "limited"
                weighted = self._fusion_weights(prof)
                contributes = reliability in ("reliable", "limited") and weighted
                note = self._signal_note(name, prof, score, contributes, weighted, padded)

                if _separation_level(prof.separation) == "unreliable":
                    direction = ("scored fake videos LOWER than real ones"
                                 if prof.separation < 0 else "barely distinguished fake from real")
                    caveats.append(Caveat(
                        f"{name.upper()}_UNRELIABLE", "warning",
                        f"The {DISPLAY[name]} signal is not trustworthy: on the FF++ test set "
                        f"(n={prof.separation_n}) it {direction} (separation {prof.separation:+.3f}). "
                        f"Its score is shown for transparency but should not be treated as evidence."
                        + ("" if prof.used_by_fusion else " It is also excluded from the Fusion input.")))
                elif not weighted:
                    caveats.append(Caveat(
                        f"{name.upper()}_IGNORED_BY_FUSION", "warning",
                        f"The {DISPLAY[name]} signal is strong on its own (separation {prof.separation:+.3f}), "
                        f"but the deployed Fusion model gives it no weight (removing it changed accuracy by "
                        f"{prof.fusion_reliance_pts:.1f} points), so it did not influence this verdict."))

            signals.append(SignalAssessment(name, score, reliability, contributes, prof.separation, note))

        by_name = {s.signal: s for s in signals}
        effective = [s for s in signals if s.contributes_to_verdict]

        # ---- temporal availability / validity caveats ----
        if temporal_from_still:
            caveats.append(Caveat(
                "TEMPORAL_FROM_STILL_IMAGE", "warning",
                "A Temporal score was produced from a single still image (the same frame repeated). "
                "That is not real motion evidence, so it was disregarded here, but the Fusion model "
                "already used it when computing its score."))
        if not temporal_available:
            caveats.append(Caveat(
                "TEMPORAL_UNAVAILABLE", "warning",
                ("This is a still image, so the Temporal signal (frame-to-frame consistency) does not exist. "
                 if is_image else
                 "No usable frame sequence was found for this person, so the Temporal signal is missing. ")
                + "The verdict rests on fewer signals than a video would provide."))
        if padded:
            caveats.append(Caveat(
                "TEMPORAL_WINDOW_PADDED", "warning",
                f"This person was tracked in only {inp.frames_seen} frames, fewer than the "
                f"{inp.sequence_length}-frame window the Temporal model expects. The window was padded by "
                f"repeating the last frame, so the Temporal score is less trustworthy."))

        # ---- effective-signal count ----
        if not effective:
            caveats.append(Caveat(
                "NO_EFFECTIVE_SIGNAL", "warning",
                "None of the signals the Fusion model actually relies on are both available and "
                "trustworthy for this input, so the Fusion score carries little real information."))
        elif len(effective) == 1:
            only = DISPLAY[effective[0].signal]
            caveats.append(Caveat(
                "SINGLE_SIGNAL", "warning",
                f"The verdict effectively rests on one signal ({only}). If that signal is wrong, "
                f"there is no independent evidence to correct it."))

        # ---- conflicts: a reliable signal pointing the other way ----
        conflicts = []
        for s in signals:
            if s.reliability == "reliable" and s.score is not None \
                    and abs(s.score - 0.5) >= CONFLICT_MARGIN \
                    and (s.score > DECISION_THRESHOLD) != (model_verdict == "FAKE"):
                conflicts.append(s)
                pointing = "fake" if s.score > 0.5 else "real"
                caveats.append(Caveat(
                    "SIGNAL_CONFLICT", "warning",
                    f"The {DISPLAY[s.signal]} signal (score {s.score:.2f}, a reliable signal) points to "
                    f"{pointing}, disagreeing with the {model_verdict} verdict."
                    + ("" if s.contributes_to_verdict else
                       " It did not influence the verdict, so this disagreement is not reflected in the Fusion score.")))

        # ---- quality ----
        q = inp.quality
        if q.level in ("poor", "degraded"):
            caveats.append(self._quality_caveat(q))
        elif q.level == "unknown":
            caveats.append(Caveat("QUALITY_UNKNOWN", "info", "No image-quality metadata was available for this analysis."))

        # ---- borderline score ----
        margin = abs(p - DECISION_THRESHOLD) * 2
        borderline = abs(p - DECISION_THRESHOLD) < BORDERLINE_MARGIN
        if borderline:
            caveats.append(Caveat(
                "BORDERLINE_SCORE", "warning",
                f"The Fusion score ({p:.2f}) is very close to the 0.5 decision line, so the "
                f"{model_verdict} call is close to a coin flip."))

        # ---- always-present validation context ----
        fp = self.fusion_profile
        fusion_unvalidated = (not temporal_available) and not fp.handles_missing_temporal
        if fusion_unvalidated:
            caveats.append(Caveat(
                "FUSION_NOT_VALIDATED_WITHOUT_TEMPORAL", "warning",
                "The Fusion model was never validated on inputs that lack a Temporal signal, so its "
                "score here is an extrapolation, not a tested prediction."))
        if fp.test_accuracy is not None:
            caveats.append(Caveat(
                "LIMITED_VALIDATION", "info",
                f"In independent testing the Fusion model was right {fp.test_accuracy * 100:.1f}% of the time"
                + (f" (AUC {fp.test_auc:.2f})" if fp.test_auc is not None else "")
                + (f" on only {fp.test_n} videos" if fp.test_n else "")
                + ". Treat any verdict as a lead to verify, not proof."))

        # ---- verdict + confidence (deterministic) ----
        base_idx = 2 if margin >= 0.6 else 1 if margin >= 0.3 else 0
        cap = 2
        drops = 0
        reasons: List[str] = []

        if not effective:
            cap = 0
            reasons.append("no trustworthy signal that Fusion relies on is available")
        elif len(effective) == 1:
            cap = 1
            reasons.append("verdict rests on a single signal")
        if not temporal_available:
            reasons.append("Temporal signal unavailable")
        if fusion_unvalidated:
            cap = 0
            reasons.append("Fusion model was not validated on inputs without a Temporal signal")
        if fp.test_accuracy is not None and fp.test_accuracy < FUSION_MAX_HIGH_ACCURACY:
            cap = min(cap, 1)
            reasons.append(f"Fusion model's independent-test accuracy is only {fp.test_accuracy * 100:.1f}%")
        if padded:
            drops += 1
            reasons.append("Temporal window was padded")
        if conflicts:
            drops += 1
            reasons.append("a reliable signal disagrees with the verdict")
        if q.level == "poor":
            drops += 1
            reasons.append("poor image quality")
        if borderline:
            cap = 0
            reasons.append("score too close to the decision line")

        idx = max(0, min(base_idx, cap) - drops)
        verdict = "INCONCLUSIVE" if (not effective or borderline or fusion_unvalidated) else model_verdict
        if verdict == "INCONCLUSIVE":
            idx = 0

        caveats.sort(key=lambda c: 0 if c.severity == "warning" else 1)
        return _Assessment(verdict, model_verdict, LEVELS[idx], reasons, signals, caveats, q.level)

    def _fusion_weights(self, prof: SignalProfile) -> bool:
        """Does Fusion actually use this signal? Unmeasured reliance gets the benefit of the doubt."""
        if not prof.used_by_fusion:
            return False
        return prof.fusion_reliance_pts is None or prof.fusion_reliance_pts >= FUSION_RELIANCE_MIN_PTS

    def _signal_note(self, name, prof, score, contributes, weighted, padded) -> str:
        n = prof.separation_n
        sep_level = _separation_level(prof.separation)
        parts = [f"{DISPLAY[name]}: score {score:.2f} (probability fake)."]
        if sep_level == "reliable":
            parts.append(f"Reliable: separates fake from real clearly on the FF++ test set "
                         f"(separation {prof.separation:+.3f}, n={n}).")
        elif sep_level == "limited":
            parts.append(f"Weak: only modest separation on the FF++ test set ({prof.separation:+.3f}, n={n}).")
        else:
            parts.append(f"Unreliable: on the FF++ test set (n={n}) fake and real scores differ by only "
                         f"{prof.separation:+.3f}, so treat this score as noise.")
        if padded and name == "temporal":
            parts.append("The frame window was padded, which lowers trust further.")
        if not prof.used_by_fusion:
            parts.append("Not an input to the Fusion model, so it did not affect the verdict.")
        elif not weighted:
            parts.append(f"The deployed Fusion model gives it no weight (removing it changed accuracy by "
                         f"{prof.fusion_reliance_pts:.1f} pts), so it did not affect the verdict.")
        elif contributes and prof.fusion_reliance_pts is not None:
            parts.append(f"Fusion relies on it (removing it costs {prof.fusion_reliance_pts:.1f} pts of accuracy).")
        return " ".join(parts)

    @staticmethod
    def _quality_caveat(q: QualitySummary) -> Caveat:
        total = q.total_input_frames or 0
        text = (f"Image quality is {q.level}: {q.removed_extreme_blur} of {total} frames were discarded as "
                f"too blurry and {q.soft_fraction * 100:.0f}% of the remaining frames are soft. Blur can "
                f"distort both visual and motion cues (note: blur is measured on the whole frame, not just the face).")
        return Caveat("LOW_QUALITY" if q.level == "poor" else "DEGRADED_QUALITY",
                      "warning" if q.level == "poor" else "info", text)

    @staticmethod
    def _overall(results: List[TrackReasoning]):
        fakes = [t for t in results if t.verdict == "FAKE"]
        if fakes:
            best = max(fakes, key=lambda t: (LEVELS.index(t.confidence), t.fusion_prob_fake))
            return "FAKE", best.confidence, best.track_id
        inconc = [t for t in results if t.verdict == "INCONCLUSIVE"]
        if inconc:
            return "INCONCLUSIVE", "Low", max(inconc, key=lambda t: t.fusion_prob_fake).track_id
        weakest = min(LEVELS.index(t.confidence) for t in results)
        return "REAL", LEVELS[weakest], max(results, key=lambda t: t.fusion_prob_fake).track_id

    # ------------------------------------------------------------------
    # Explanation: LLM with strict validation, rule-based fallback
    # ------------------------------------------------------------------
    def _explain(self, inp: ReasoningInput, a: _Assessment):
        if self.llm is not None:
            try:
                raw = self.llm.complete(SYSTEM_PROMPT, json.dumps(self._payload(inp, a)))
                data = _parse_llm_json(raw)
                text = data.get("explanation")
                if data.get("verdict") != a.verdict:
                    raise ValueError(f"LLM verdict {data.get('verdict')!r} != fixed verdict {a.verdict!r}")
                if not isinstance(text, str) or not text.strip():
                    raise ValueError("empty explanation")
                if len(text) > MAX_EXPLANATION_CHARS:
                    raise ValueError("explanation too long")
                return text.strip(), "llm"
            except Exception as e:
                logger.warning("Agentic reasoning: LLM explanation rejected (%s); using rule-based.", e)
        return self._rule_based_explanation(inp, a), "rule_based"

    def _payload(self, inp: ReasoningInput, a: _Assessment) -> dict:
        fp = self.fusion_profile
        return {
            "verdict": a.verdict,
            "model_verdict": a.model_verdict,
            "confidence": a.confidence,
            "confidence_reasons": a.confidence_reasons,
            "fusion_prob_fake": round(inp.fusion_prob_fake, 3),
            "input_type": inp.input_type,
            "signals": [{"signal": s.signal,
                         "score": None if s.score is None else round(s.score, 3),
                         "reliability": s.reliability,
                         "contributes_to_verdict": s.contributes_to_verdict,
                         "note": s.note} for s in a.signals],
            "caveats": [asdict(c) for c in a.caveats],
            "quality": {"level": a.quality_level},
            "fusion_test_performance": {"accuracy": fp.test_accuracy, "auc": fp.test_auc, "n_videos": fp.test_n},
        }

    @staticmethod
    def _rule_based_explanation(inp: ReasoningInput, a: _Assessment) -> str:
        subject = "image" if inp.input_type == "image" else "person in this video"
        used = [DISPLAY[s.signal] for s in a.signals if s.contributes_to_verdict]
        warnings = [c.text for c in a.caveats if c.severity == "warning"]

        if a.verdict == "INCONCLUSIVE":
            head = (f"The system cannot make a reliable call on this {subject} "
                    f"(Fusion score {inp.fusion_prob_fake:.2f}).")
            basis = ""
        else:
            word = "manipulated" if a.verdict == "FAKE" else "authentic"
            head = (f"The system rates this {subject} as likely {word} "
                    f"(Fusion score {inp.fusion_prob_fake:.2f}) with {a.confidence.lower()} confidence.")
            basis = (f" This rests on the {' and '.join(used)} signal{'s' if len(used) > 1 else ''}."
                     if used else "")
        body = " ".join(warnings[:3])
        return f"{head}{basis} {body} This is an automated estimate, not proof.".replace("  ", " ").strip()


