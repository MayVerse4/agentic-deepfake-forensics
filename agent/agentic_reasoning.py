@dataclass
class QualitySummary:
    """
    Aggregated from quality_checker.py output.

    NOTE on naming in quality_checker.py: blur_level "low" means LOW BLUR
    (i.e. sharp), "medium" is soft, "extreme" frames are removed before
    they reach any model. Blur is measured on the whole original frame,
    not on the face crop.
    """
    available: bool = False
    total_input_frames: Optional[int] = None
    kept_frames: Optional[int] = None
    removed_extreme_blur: int = 0
    removed_error: int = 0
    sharp_frames: int = 0      # blur_level == "low"
    soft_frames: int = 0       # blur_level == "medium"
    mean_blur_score: Optional[float] = None   # Laplacian variance, higher = sharper
    min_blur_score: Optional[float] = None

    @classmethod
    def from_frame_data(cls, frame_data: List[dict], stats: Optional[dict] = None) -> "QualitySummary":
        """Call with the frame_data returned by QualityChecker.process_frames() and its stats dict."""
        stats = stats or {}
        sharp = soft = 0
        scores: List[float] = []
        for fd in frame_data:
            lvl = fd.get("blur_level")
            if lvl == "low":
                sharp += 1
            elif lvl == "medium":
                soft += 1
            s = fd.get("blur_score")
            if s is not None:
                scores.append(float(s))
        return cls(
            available=bool(stats) or bool(scores),
            total_input_frames=stats.get("total_input"),
            kept_frames=stats.get("kept", len(frame_data)),
            removed_extreme_blur=int(stats.get("removed_extreme_blur", 0)),
            removed_error=int(stats.get("removed_error", 0)),
            sharp_frames=sharp,
            soft_frames=soft,
            mean_blur_score=(sum(scores) / len(scores)) if scores else None,
            min_blur_score=min(scores) if scores else None,
        )

    @property
    def removed_fraction(self) -> float:
        total = self.total_input_frames or 0
        return self.removed_extreme_blur / total if total else 0.0

    @property
    def soft_fraction(self) -> float:
        kept = self.kept_frames or 0
        return self.soft_frames / kept if kept else 0.0

    @property
    def level(self) -> str:
        if not self.available:
            return "unknown"
        if self.removed_fraction >= QUALITY_POOR_REMOVED_FRAC or self.soft_fraction >= QUALITY_POOR_BLURRY_FRAC:
            return "poor"
        if self.removed_fraction >= QUALITY_DEGRADED_REMOVED_FRAC or self.soft_fraction >= QUALITY_DEGRADED_BLURRY_FRAC:
            return "degraded"
        return "good"

    def to_dict(self) -> dict:
        d = asdict(self)
        d["level"] = self.level
        return d


@dataclass
class ReasoningInput:
    """One person/track's worth of evidence. Scores are P(fake) in [0, 1]."""
    track_id: Any
    fusion_prob_fake: float
    spatial_prob_fake: Optional[float] = None
    frequency_prob_fake: Optional[float] = None
    temporal_prob_fake: Optional[float] = None   # raw, as InferenceEngine produced it
    input_type: str = "video"                    # "image" | "video"
    frames_seen: Optional[int] = None
    sequence_length: Optional[int] = None        # Config.SEQUENCE_LENGTH
    quality: QualitySummary = field(default_factory=QualitySummary)

    @classmethod
    def from_engine_output(cls, engine_output: dict, track: dict,
                           quality: Optional[QualitySummary] = None,
                           sequence_length: Optional[int] = None) -> "ReasoningInput":
        return cls(
            track_id=track.get("track_id"),
            fusion_prob_fake=float(track["combined_prob_fake"]),
            spatial_prob_fake=track.get("spatial_prob_fake"),
            frequency_prob_fake=track.get("frequency_prob_fake"),
            temporal_prob_fake=track.get("temporal_prob_fake"),
            input_type=engine_output.get("input_type", "video"),
            frames_seen=track.get("frames_seen"),
            sequence_length=sequence_length,
            quality=quality or QualitySummary(),
        )


